"""Compare two broad-HTTP battery captures and report behavioural differences.

The battery records status, the complete response header map and the decoded
representation. `Date` is excluded (the two runs happen seconds apart);
everything else must match exactly, except for the deliberate differences listed
in the rules below, which are reported as `known` (never silently ignored) and
rejected by `--strict` so the allowlist can be audited on its own.

Every allowance is a *stated deployment contract* difference, not an excuse for
a missing nginx semantic:

- `Server` — the reference build always appends `nginx/<version>`; the runtime
  is an nginx-compatible edge, not nginx, and never advertises an implementation
  banner. The header doubles as the identity witness for each side.
- `Cache-Control` — ENVIRONMENT_SPEC section 13 / SDKWORK_DEPLOY_SPEC section
  8.1: a static representation with no `expires` declares `public, no-cache` so
  shared caches revalidate instead of caching heuristically. nginx has no
  equivalent default; a configured `expires` replaces the value and then matches
  byte for byte.
- `X-Content-Type-Options` — SECURITY_SPEC "secure response headers" requires
  `nosniff`; nginx only sends it when configured.
- `Vary: User-Agent, Sec-CH-UA-Mobile` on an SPA-fallback route —
  APP_RUNTIME_TOPOLOGY_SPEC adaptive ingress requires the device-class
  representation selectors to be declared on every adaptive-surface response.
- `www-authenticate` charset parameter — RFC 7617 section 2.1 allows (and
  recommends) `charset="UTF-8"` on a Basic challenge; nginx omits it.
- `x-drop` on a proxied response — RFC 9110 section 7.6.1 requires a proxy to
  remove hop-by-hop fields named by `Connection`; nginx 1.29.6 forwards them,
  the runtime removes them (the strict form is asserted by
  tests/nginx/full-surface and by the runtime's own unit tests).
- nginx's generated error page — the reference build renders a generated HTML
  page embedding its version banner; the runtime answers the same status with its
  own diagnostic body. Status, `Content-Range` and every request/cache header
  still match exactly. Only allowed when the oracle body is recognisably nginx's
  generated page.
- a duplicated `always` add_header field on nginx's internally generated 416
  page — nginx re-enters its headers filter for the range-filter failure, so the
  field appears twice with the same value; the runtime emits it once (RFC 9110
  section 5.3 allows the field to be combined, and the value is identical).
- a body generated by `return <status> <text>` — the typed runtime resource
  declares `respondResource.contentType` defaulting to
  `text/plain; charset=utf-8` (config schema). nginx instead derives the type
  from the request URI extension, which the runtime does not model.
- an unknown file extension — the runtime's MIME fallback is the safe
  `application/octet-stream` (PRD-runtime-core "MIME and charset mapping with
  safe fallback"), nginx's built-in `default_type` is `text/plain`.
- `Content-Type` on a bodyless 204 — the typed respond resource names its
  content type explicitly even when the status carries no body; nginx omits the
  header entirely.

    python compare.py --expected nginx-oracle.json --actual ours.json
    python compare.py --expected nginx-oracle.json --actual ours.json --strict

Exit status is 0 when every case matches or is a known difference, 1 otherwise.
"""

from __future__ import annotations

import argparse
import json
import sys

# `Date` is the only response header that always differs between the two
# sequential runs; every freshness-sensitive header was pinned by the battery
# and is compared exactly.
IGNORED_HEADERS = frozenset({"date"})

# The nginx generated error page carries these; the runtime's own diagnostic body
# is not the nginx template, so their values may differ together.
ERROR_PAGE_HEADERS = frozenset(
    {
        "content-length",
        "content-type",
        "etag",
        "last-modified",
        "accept-ranges",
        "content-range",
    }
)


def media_type(value: str) -> str:
    return value.split(";", 1)[0].strip().lower()


def normalize_vary(value) -> str | None:
    """`Vary` is a case-insensitive list of header names (RFC 9110 section 12.5.5)."""
    if value is None:
        return None
    return ", ".join(
        sorted(token.strip().lower() for token in value.split(",") if token.strip())
    )


def status_of(record) -> int:
    status = record.get("status")
    return status if isinstance(status, int) else 0


def generated_error_page(record) -> bool:
    return bool(record.get("nginx_error_page"))


def known_header_reason(case, name, expected, actual, expected_record, actual_record):
    if name == "server":
        if isinstance(expected, str) and expected.startswith("nginx/") and actual is None:
            return (
                "the runtime never advertises an implementation banner; the reference "
                "build always appends its nginx version (recorded as the identity witness)"
            )
        return None
    if name == "cache-control":
        if expected is None and actual == "public, no-cache":
            return (
                "deployment freshness policy (ENVIRONMENT_SPEC section 13): static "
                "representations without `expires` declare `public, no-cache` so shared "
                "caches revalidate; a configured `expires` still matches exactly"
            )
        return None
    if name == "x-content-type-options":
        if expected is None and actual == "nosniff":
            return (
                "SECURITY_SPEC secure response headers: the runtime emits nosniff by "
                "default; nginx only when explicitly configured"
            )
        return None
    if name == "vary":
        if (
            expected is None
            and actual == "User-Agent, Sec-CH-UA-Mobile"
            and case.startswith("route.try-files")
        ):
            return (
                "APP_RUNTIME_TOPOLOGY_SPEC adaptive ingress: an SPA-fallback route "
                "declares the device-class representation selectors so shared caches "
                "never mix PC and H5 renderings; nginx try_files has no equivalent"
            )
        return None
    if name == "www-authenticate":
        if (
            isinstance(expected, str)
            and isinstance(actual, str)
            and actual == expected + ', charset="UTF-8"'
        ):
            return (
                "RFC 7617 section 2.1: the runtime declares the charset of a Basic "
                "challenge explicitly; nginx omits the parameter"
            )
        return None
    if name == "x-drop":
        if expected is not None and actual is None:
            return (
                "RFC 9110 section 7.6.1: a proxy removes hop-by-hop fields named by "
                "`Connection`; nginx 1.29.6 forwards them, the runtime removes them"
            )
        return None
    if generated_error_page(expected_record) and name in ERROR_PAGE_HEADERS:
        return (
            "nginx renders its generated error page, which embeds the nginx version "
            "banner; the runtime answers the same status with its own diagnostic body "
            "while status and every request/cache header match"
        )
    if status_of(expected_record) == 416 and isinstance(expected, str):
        # nginx's headers filter also runs once before its range filter turns
        # the response into the generated 416 page: an `always` field is then
        # emitted a second time on the error pass, and a non-`always` field
        # reflects the earlier 200 status. The runtime applies `add_header`
        # exactly once, to the final status.
        if isinstance(actual, str) and expected == actual + "\n" + actual:
            return (
                "nginx runs its headers filter twice for the internally generated 416 "
                "range-failure page, emitting an `always` add_header field twice; the "
                "runtime emits the identical field once"
            )
        if actual is None:
            return (
                "nginx's first headers-filter pass ran while the range response was still "
                "a 200, so a non-`always` add_header field is emitted on its generated 416 "
                "page; the runtime applies add_header once, to the final 416 status"
            )
    if name == "content-type" and isinstance(expected, str) and isinstance(actual, str):
        expected_media = media_type(expected)
        actual_media = media_type(actual)
        if expected_media == actual_media and expected != actual:
            return (
                "the typed respond resource declares `text/plain; charset=utf-8` by "
                "default (config schema), so a synthesised textual body carries the "
                "charset parameter"
            )
        if (
            expected_media != actual_media
            and actual.startswith("text/plain")
            and expected_record.get("body_sha256") == actual_record.get("body_sha256")
        ):
            return (
                "nginx derives a `return` body's content type from the request URI "
                "extension; the typed respond resource declares its content type "
                "explicitly, and the body bytes are identical"
            )
        if actual_media == "application/octet-stream":
            return (
                "the runtime's unknown-extension fallback is the safe "
                "`application/octet-stream` (PRD-runtime-core safe MIME fallback); "
                "nginx's built-in `default_type` is `text/plain`"
            )
    if name == "content-type" and expected is None and actual is not None:
        if status_of(expected_record) == 204 and actual.startswith("text/plain"):
            return (
                "the typed respond resource names its content type explicitly even for "
                "a bodyless 204; nginx omits Content-Type entirely"
            )
    return None


def known_body_reason(expected_record):
    if generated_error_page(expected_record):
        return (
            "nginx renders its generated error page, which embeds the nginx version "
            "banner; the runtime answers the same status with its own diagnostic body "
            "while status and every request/cache header match"
        )
    return None


def compare_records(case, expected, actual, failures, known):
    if expected.get("status") != actual.get("status"):
        failures.append((case, "status", expected.get("status"), actual.get("status")))

    expected_headers = expected.get("headers", {})
    actual_headers = actual.get("headers", {})
    for name in sorted(set(expected_headers) | set(actual_headers)):
        if name in IGNORED_HEADERS:
            continue
        left = expected_headers.get(name)
        right = actual_headers.get(name)
        if name == "vary":
            if normalize_vary(left) == normalize_vary(right):
                continue
        elif left == right:
            continue
        reason = known_header_reason(
            case, name, left, right, expected, actual
        )
        if reason is None:
            failures.append((case, "header:" + name, left, right))
        else:
            known.append((case, "header:" + name, left, right, reason))

    # Multipart range bodies are compared structurally; the boundary token and
    # the per-part CRLF framing are canonicalised away by the battery.
    expected_multipart = expected.get("multipart")
    actual_multipart = actual.get("multipart")
    if expected_multipart is not None or actual_multipart is not None:
        if expected_multipart != actual_multipart:
            failures.append((case, "multipart", expected_multipart, actual_multipart))
        return

    for field in ("body_len", "body_sha256"):
        left = expected.get(field)
        right = actual.get(field)
        if left == right:
            continue
        reason = known_body_reason(expected)
        if reason is None:
            failures.append((case, field, left, right))
        else:
            known.append((case, field, left, right, reason))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--expected", required=True)
    parser.add_argument("--actual", required=True)
    parser.add_argument("--label-expected", default="nginx")
    parser.add_argument("--label-actual", default="ours")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="treat the documented differences as failures, to audit the allowlist",
    )
    args = parser.parse_args()

    expected = json.load(open(args.expected, encoding="utf-8"))
    actual = json.load(open(args.actual, encoding="utf-8"))

    cases = sorted(
        key for key in set(expected) | set(actual) if not key.startswith("_")
    )
    failures: list = []
    known: list = []
    for case in cases:
        if case not in expected or case not in actual:
            failures.append((case, "<case>", case in expected, case in actual))
            continue
        compare_records(case, expected[case], actual[case], failures, known)

    print("identity: %s server=%r" % (args.label_expected, expected.get("_server")))
    print("identity: %s server=%r" % (args.label_actual, actual.get("_server")))
    print("validators: %s etag=%r" % (args.label_expected, expected.get("_etag")))
    print("validators: %s etag=%r" % (args.label_actual, actual.get("_etag")))
    print()

    if known:
        by_reason = {}
        for case, field, left, right, reason in known:
            by_reason.setdefault(reason, []).append((case, field, left, right))
        print("known differences (%d):" % len(known))
        for reason, entries in sorted(by_reason.items()):
            print("  %d difference(s): %s" % (len(entries), reason))
            for case, field, left, right in sorted(entries)[:3]:
                print("     e.g. %s %s %r -> %r" % (case, field, left, right))
        print()

    if failures:
        for case, field, left, right in failures:
            print("FAIL %s.%s" % (case, field))
            print("     %-8s %r" % (args.label_expected, left))
            print("     %-8s %r" % (args.label_actual, right))
        print()

    matching = len(cases) - len({failure[0] for failure in failures})
    print("differential: %d/%d cases match" % (matching, len(cases)))
    print("differential: %d known difference(s)" % len(known))
    print("differential: %d unexpected difference(s)" % len(failures))

    if failures:
        return 1
    if args.strict and known:
        print("differential: --strict rejects the known differences above")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
