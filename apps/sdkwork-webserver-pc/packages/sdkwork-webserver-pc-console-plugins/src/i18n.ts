export type PluginsMessageKey = keyof typeof enUs;

const catalogs: Record<PluginsLocale, Record<PluginsMessageKey, string>> = {
  "en-US": enUs,
  "zh-CN": zhCn,
};

export function normalizePluginsLocale(locale?: string | null): PluginsLocale {
  if (!locale) return "en-US";
  const normalized = locale.trim().toLowerCase().replaceAll("_", "-");
  return normalized === "zh-cn" || normalized === "zh" || normalized.startsWith("zh-")
    ? "zh-CN"
    : "en-US";
}

export function translatePlugins(
  locale: PluginsLocale,
  key: PluginsMessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = catalogs[locale][key] ?? catalogs["en-US"][key] ?? String(key);
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  );
}
